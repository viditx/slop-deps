// Self-updating corpus pipeline — fetches the most popular packages straight
// from the registries and regenerates src/corpus.generated.js.
// The curated lists in typosquat.js always stay merged in; this adds live data
// so the typosquat engine never rots. Run: npx slop-deps --update-corpus

import { promises as fs } from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT_FILE = path.join(__dirname, 'corpus.generated.js');

// Popularity-ranked keyword sweeps — the npm search API needs non-empty text,
// so we union results across high-signal ecosystem keywords.
const NPM_SEEDS = ['javascript', 'nodejs', 'typescript', 'react', 'vue', 'cli',
  'server', 'testing', 'utils', 'webpack', 'async', 'api'];
const NPM_PAGE_SIZE = 250;

async function fetchJson(url, timeoutMs = 15000) {
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), timeoutMs);
  try {
    const res = await fetch(url, { signal: controller.signal });
    if (!res.ok) throw new Error(`HTTP ${res.status} for ${url}`);
    return await res.json();
  } finally {
    clearTimeout(timer);
  }
}

async function fetchText(url, timeoutMs = 15000) {
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), timeoutMs);
  try {
    const res = await fetch(url, { signal: controller.signal });
    if (!res.ok) throw new Error(`HTTP ${res.status} for ${url}`);
    return await res.text();
  } finally {
    clearTimeout(timer);
  }
}

const sleep = (ms) => new Promise(r => setTimeout(r, ms));

async function fetchNpmPopular() {
  const names = new Set();
  for (const seed of NPM_SEEDS) {
    const url = `https://registry.npmjs.org/-/v1/search?text=${encodeURIComponent(seed)}&size=${NPM_PAGE_SIZE}&from=0&popularity=1.0`;
    // The search API rate-limits aggressively: one retry with backoff, and a
    // failed seed keeps the names already harvested instead of failing everything.
    let data = null;
    for (let attempt = 0; attempt < 2 && !data; attempt++) {
      try {
        data = await fetchJson(url);
      } catch (err) {
        if (attempt === 1) {
          console.warn(`  npm seed "${seed}" failed (${err.message}) — continuing with partial data`);
          break;
        }
        await sleep(2000);
      }
    }
    for (const obj of data?.objects || []) {
      const name = obj?.package?.name;
      if (name && /^[a-zA-Z0-9@_.\-/]+$/.test(name)) {
        names.add(name.toLowerCase());
      }
    }
    await sleep(1200);
  }
  return [...names];
}

const PYPI_DATASET = 'https://raw.githubusercontent.com/hugovk/top-pypi-packages/main/top-pypi-packages-30-days.json';
const PYPI_TOP_N = 1000;

async function fetchPyPiPopular() {
  // Community-maintained top-PyPI dataset regenerated from official PyPI stats
  const data = await fetchJson(PYPI_DATASET);
  const rows = data?.rows || data || [];
  const names = [];
  for (const row of rows.slice(0, PYPI_TOP_N)) {
    const name = row?.project || row?.name;
    if (name && /^[a-zA-Z0-9_.\-]+$/.test(name)) {
      names.push(String(name).toLowerCase());
    }
  }
  return [...new Set(names)];
}

function header(count, source) {
  return `// AUTO-GENERATED by \`slop-deps --update-corpus\` — do not edit by hand.
// Source: ${source}. Merged (not replaced) with the curated lists in typosquat.js
// at import time, so hand-curated entries always survive regeneration.
`;
}

export async function updateCorpus() {
  const [npmNames, pypiNames] = await Promise.all([
    fetchNpmPopular().catch(err => {
      console.warn(`  npm corpus fetch failed (${err.message}) — writing curated-only npm section`);
      return [];
    }),
    fetchPyPiPopular().catch(err => {
      console.warn(`  PyPI corpus fetch failed (${err.message}) — writing curated-only pypi section`);
      return [];
    })
  ]);

  const body = `${header(`npm registry search (${npmNames.length} names) + pypi.org/top (${pypiNames.length} names)`)}

export const NPM_GENERATED = ${JSON.stringify(npmNames, null, 0)};

export const PYPI_GENERATED = ${JSON.stringify(pypiNames, null, 0)};
`;

  await fs.writeFile(OUT_FILE, body, 'utf-8');
  return { npm: npmNames.length, pypi: pypiNames.length, file: OUT_FILE };
}
