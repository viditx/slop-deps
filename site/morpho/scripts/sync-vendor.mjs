import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const repoRoot = path.resolve(__dirname, '../../..');
const vendorDir = path.resolve(__dirname, '../src/vendor/slop-deps');

async function syncVendor() {
  console.log('🔄 Syncing vendor files from core CLI to site/morpho...');

  // 1. Load generated corpus and base lists from CLI
  const genPath = path.join(repoRoot, 'src/corpus.generated.js');
  const typoPath = path.join(repoRoot, 'src/typosquat.js');

  const gen = await import(`file:///${genPath.replace(/\\/g, '/')}`);
  const typoCode = fs.readFileSync(typoPath, 'utf8');

  const extractArr = (name) => {
    const m = typoCode.match(new RegExp('const ' + name + ' = ([\\s\\S]*?);\\n\\n'));
    if (!m) return [];
    return eval(m[1]);
  };

  const npmBase = extractArr('NPM_POPULAR');
  const pypiBase = extractArr('PYPI_POPULAR');
  const rustBase = extractArr('RUST_POPULAR');

  const allNpm = [...new Set([...npmBase, ...(gen.NPM_GENERATED || [])])].sort();
  const allPypi = [...new Set([...pypiBase, ...(gen.PYPI_GENERATED || [])])].sort();
  const allCrates = [...new Set(rustBase)].sort();

  console.log(`  ✓ npm packages: ${allNpm.length}`);
  console.log(`  ✓ pypi packages: ${allPypi.length}`);
  console.log(`  ✓ crates packages: ${allCrates.length}`);

  const targetCorpusPath = path.join(vendorDir, 'corpus.generated.js');
  const corpusContent = `// Auto-generated by scripts/sync-vendor.mjs — pure ESM corpus for web scanner
export const NPM_POPULAR = ${JSON.stringify(allNpm, null, 2)};

export const PYPI_POPULAR = ${JSON.stringify(allPypi, null, 2)};

export const CRATES_POPULAR = ${JSON.stringify(allCrates, null, 2)};

export const CORPUS = {
  npm: NPM_POPULAR,
  pypi: PYPI_POPULAR,
  crates: CRATES_POPULAR,
};

export default CORPUS;
`;

  fs.writeFileSync(targetCorpusPath, corpusContent, 'utf8');
  console.log(`  ✔ Written ${targetCorpusPath} (${Buffer.byteLength(corpusContent)} bytes)`);

  console.log('🎉 Vendor sync complete!');
}

syncVendor().catch((err) => {
  console.error('❌ Vendor sync failed:', err);
  process.exit(1);
});
