import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const repoRoot = path.resolve(__dirname, '../../..');
const vendorDir = path.resolve(__dirname, '../src/vendor/slop-deps');

async function syncVendor() {
  console.log('🔄 Syncing vendor files from core CLI to site/morpho...');

  // 1. Safe ESM import of base popular lists and generated corpus (NO eval)
  const genPath = path.join(repoRoot, 'src/corpus.generated.js');
  const typoPath = path.join(repoRoot, 'src/typosquat.js');

  const gen = await import(`file:///${genPath.replace(/\\/g, '/')}`);
  const typoModule = await import(`file:///${typoPath.replace(/\\/g, '/')}`);

  const npmBase = typoModule.NPM_POPULAR || [];
  const pypiBase = typoModule.PYPI_POPULAR || [];
  const rustBase = typoModule.RUST_POPULAR || [];

  const allNpm = [...new Set([...npmBase, ...(gen.NPM_GENERATED || [])])].sort();
  const allPypi = [...new Set([...pypiBase, ...(gen.PYPI_GENERATED || [])])].sort();
  const allCrates = [...new Set(rustBase)].sort();

  console.log(`  ✓ npm packages: ${allNpm.length}`);
  console.log(`  ✓ pypi packages: ${allPypi.length}`);
  console.log(`  ✓ crates packages: ${allCrates.length}`);

  // 2. Generate unified web corpus
  const targetCorpusPath = path.join(vendorDir, 'corpus.generated.js');
  const corpusContent = `// Auto-generated by scripts/sync-vendor.mjs — pure ESM corpus for web scanner
export const NPM_POPULAR = ${JSON.stringify(allNpm, null, 2)};

export const PYPI_POPULAR = ${JSON.stringify(allPypi, null, 2)};

export const CRATES_POPULAR = ${JSON.stringify(allCrates, null, 2)};

export const CORPUS = {
  npm: NPM_POPULAR,
  pypi: PYPI_POPULAR,
  crates: CRATES_POPULAR,
};

export default CORPUS;
`;

  fs.writeFileSync(targetCorpusPath, corpusContent, 'utf8');
  console.log(`  ✔ Written ${path.basename(targetCorpusPath)} (${Buffer.byteLength(corpusContent)} bytes)`);

  // 3. Sync all core AST extractors and verification modules directly (Zero Vendor Drift)
  const filesToSync = [
    { src: 'src/builtins.js', dest: 'builtins.js' },
    { src: 'src/pypi-map.js', dest: 'pypi-map.js' },
    { src: 'src/typosquat.js', dest: 'typosquat.js' },
    { src: 'src/extractors/manifests.js', dest: 'manifests.js' },
    { src: 'src/extractors/js-ts.js', dest: 'js-ts.js' },
    { src: 'src/extractors/python.js', dest: 'python.js' },
    { src: 'src/extractors/rust.js', dest: 'rust.js' },
  ];

  for (const { src, dest } of filesToSync) {
    const srcPath = path.join(repoRoot, src);
    const destPath = path.join(vendorDir, dest);
    const content = fs.readFileSync(srcPath, 'utf8');
    fs.writeFileSync(destPath, content, 'utf8');
    console.log(`  ✔ Synced ${src} -> ${dest} (${Buffer.byteLength(content)} bytes)`);
  }

  console.log('🎉 Vendor sync complete — Zero M-3 drift guaranteed!');
}

syncVendor().catch((err) => {
  console.error('❌ Vendor sync failed:', err);
  process.exit(1);
});
